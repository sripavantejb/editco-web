/**
 * Tailwind v4's oxide WASM scanner cannot read the Windows filesystem under
 * Application Control / WASI, so utility classes never get generated.
 * This script reads sources in JS, extracts candidates via oxide.scanFiles,
 * and writes @source inline(...) rules for PostCSS to consume.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, extname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

process.env.NAPI_RS_FORCE_WASI = "true";

const require = createRequire(import.meta.url);
const { Scanner } = require("@tailwindcss/oxide");

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const srcRoot = join(root, "src");
const outFile = join(root, "src", "app", "generated-tw-sources.css");

const EXTS = new Set([".tsx", ".ts", ".jsx", ".js", ".css", ".mdx"]);

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === ".next" || name === "generated-tw-sources.css") {
      continue;
    }
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, files);
    else if (EXTS.has(extname(name))) files.push(full);
  }
  return files;
}

function chunk(arr, size) {
  const out = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
}

const scanner = new Scanner({
  sources: [{ base: root, pattern: "**/*", negated: false }],
});

const files = walk(srcRoot);
const candidates = new Set();

for (const file of files) {
  const extension = extname(file).slice(1); // tsx without dot
  const content = readFileSync(file, "utf8");
  const found = scanner.scanFiles([
    {
      path: relative(root, file).replace(/\\/g, "/"),
      content,
      extension,
    },
  ]);
  for (const c of found) candidates.add(c);
}

const list = [...candidates].sort();
const lines = [
  "/* AUTO-GENERATED by scripts/generate-tw-sources.mjs — do not edit */",
  `/* ${list.length} candidates from ${files.length} files */`,
];

for (const group of chunk(list, 400)) {
  // Escape backslashes and quotes for CSS string
  const body = group.map((c) => c.replace(/\\/g, "\\\\").replace(/"/g, '\\"')).join(" ");
  lines.push(`@source inline("${body}");`);
}

writeFileSync(outFile, lines.join("\n") + "\n", "utf8");
console.log(
  `[generate-tw-sources] ${list.length} classes → ${relative(root, outFile)}`
);
